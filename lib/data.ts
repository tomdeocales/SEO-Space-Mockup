export function getCategoryScore(category: string, competitor: "semrush" | "peec"): number {
  const categoryFeatures = features.filter((f) => f.category === category)
  if (categoryFeatures.length === 0) return 0

  const totalPossible = categoryFeatures.length * 2
  const seoSpaceTotal = categoryFeatures.reduce((sum, f) => sum + f.seoSpace, 0)
  const competitorTotal = categoryFeatures.reduce((sum, f) => sum + f[competitor], 0)

  // Calculate how SEO Space compares
  const parityRatio = competitorTotal > 0 ? (seoSpaceTotal / competitorTotal) * 100 : 100
  return Math.min(100, Math.round(parityRatio))
}

export function getOverallParityScore(competitor: "semrush" | "peec"): number {
  const seoSpaceTotal = features.reduce((sum, f) => sum + f.seoSpace, 0)
  const competitorTotal = features.reduce((sum, f) => sum + f[competitor], 0)

  const parityRatio = competitorTotal > 0 ? (seoSpaceTotal / competitorTotal) * 100 : 100
  return Math.min(100, Math.round(parityRatio))
}

export function getFeaturesBehind(competitor: "semrush" | "peec"): number {
  return features.filter((f) => f.seoSpace < f[competitor]).length
}

export function getFeaturesAhead(competitor: "semrush" | "peec"): number {
  return features.filter((f) => f.seoSpace > f[competitor]).length
}

export function getHighPriorityGaps(competitor: "semrush" | "peec"): number {
  return features.filter((f) => f.seoSpace < f[competitor] && f.priorityScore >= 85).length
}

